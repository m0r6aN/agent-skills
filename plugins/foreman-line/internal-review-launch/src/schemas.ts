/** Reuse the frozen shared UUID primitive; no new identity/hash authority scheme. */
const uuid = correlationSchema.properties.runId
const text = { type: 'string', minLength: 1 }
const bool = { type: 'boolean' }
const integer = (minimum = 0, maximum = Number.MAX_SAFE_INTEGER) => ({
  type: 'integer',
  minimum,
  maximum,
})
const fixed = (value: string | readonly string[]) => ({ const: value })
const choices = (...values: string[]) => ({ type: 'string', enum: values })
const digest = { type: 'string', pattern: '^[0-9a-f]{64}$' }
const commit = { type: 'string', pattern: '^[0-9a-f]{40}$' }
const closed = <T extends Record<string, object>>(properties: T) => ({
  type: 'object',
  additionalProperties: false,
  required: Object.keys(properties),
  properties,
})
const evidence = closed({
  ref: text,
  status: choices('present', 'unknown', 'contradicted'),
  issuedAtEpochMs: integer(),
  expiresAtEpochMs: integer(),
  changed: bool,
  revoked: bool,
})
const model = (modelId: string) =>
  closed({
    provider: fixed('anthropic'),
    modelId: fixed(modelId),
    family: text,
    tier: fixed('frontier'),
    contextTokens: integer(200_000),
    tools: fixed(['read_evidence']),
    plainFindings: bool,
    qualitySuitable: bool,
    reviewSuitable: bool,
    reasoning: closed({ requested: text, nativeMaximum: text, mappingVerified: bool, evidence }),
    evidence,
  })

